#: Path → the function that generates it.
GENERATED: Final[Mapping[str, Any]] = {
    "format.md": format_markdown,
    "cli.md": cli_markdown,
    "theme.md": theme_markdown,
}


def generate() -> dict[Path, str]:
    """Every generated reference, as path → intended content."""
    return {DOCS_DIR / name: build() for name, build in GENERATED.items()}


def stale(documents: Mapping[Path, str] | None = None) -> list[Path]:
    """The generated documents whose committed content is not what we would write."""
    documents = documents if documents is not None else generate()
    return [
        path
        for path, content in documents.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift, write nothing")
    arguments = parser.parse_args(argv)

    documents = generate()
    outdated = stale(documents)
    if arguments.check:
        for path in outdated:
            print(f"stale: {path.relative_to(ROOT)} — run `make docs`")
        return 1 if outdated else 0

    for path, content in documents.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
