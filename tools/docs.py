# ---------------------------------------------------------------------------
# Small markdown helpers
# ---------------------------------------------------------------------------


def _cell(text: str) -> str:
    """One table cell: no newlines, and no pipe that would end the column."""
    return " ".join(text.split()).replace("|", "\\|")


def _table(headings: Sequence[str], rows: Iterable[Sequence[str]]) -> list[str]:
    """A GitHub-flavoured table, or nothing at all when there are no rows."""
    body = [f"| {' | '.join(_cell(value) for value in row)} |" for row in rows]
    if not body:
        return []
    return [
        f"| {' | '.join(headings)} |",
        f"|{'|'.join('---' for _ in headings)}|",
        *body,
    ]


def _block(lines: Sequence[str]) -> list[str]:
    """A section followed by one blank line, or nothing when it is empty."""
    return [*lines, ""] if lines else []


def _code(values: Iterable[str]) -> str:
    return ", ".join(f"`{value}`" for value in values)


def _number(value: float) -> str:
    """Render a float the way a theme file would write it."""
    return str(int(value)) if value == int(value) else str(value)


def _value(value: object) -> str:
    """One theme value, as it appears in TOML — floats keep their point."""
    if isinstance(value, Padding):
        sides = (value.top, value.right, value.bottom, value.left)
        return f"`[{', '.join(repr(side) for side in sides)}]`"
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, float):
        return f"`{value!r}`"
    if isinstance(value, tuple):
        return f"`[{', '.join(_quoted(item) for item in value)}]`"
    if isinstance(value, str):
        return f'`"{value}"`'
    return f"`{value}`"


def _quoted(value: object) -> str:
    return f'"{value}"' if isinstance(value, str) else str(value)


# ---------------------------------------------------------------------------
# docs/format.md — the document format, from the field tables
# ---------------------------------------------------------------------------


def _field_type(field: FieldSpec) -> str:
    """A field's type and its constraints, as one phrase.

    Type and constraint are one column on purpose: `array of node, at least 1`
    is the whole answer to "what may I write here", and splitting it across two
    columns makes a reader assemble it.
    """
    if field.enum:
        described = f"string — one of {_code(field.enum)}"
    elif field.kind == "array" and field.item_ref:
        described = f"array of [{field.item_ref}](#{field.item_ref}-object)"
    elif field.kind == "array" and field.item_kind == "point":
        described = "array of `[x, y]` pairs"
    elif field.kind == "array" and field.item_kind:
        described = f"array of {field.item_kind}"
    elif field.kind == "object" and field.ref:
        described = f"[{field.ref} object](#{field.ref}-object)"
    else:
        described = field.kind

    if field.min_items:
        described += f", at least {field.min_items}"
    if field.exclusive_minimum is not None:
        described += f", greater than {_number(field.exclusive_minimum)}"
    return described


def _field_rows(fields: Iterable[FieldSpec]) -> list[list[str]]:
    return [
        [
            f"`{field.name}`",
            _field_type(field),
            "**yes**" if field.required else "no",
            field.description,
        ]
        for field in fields
    ]


def _fields_table(fields: Iterable[FieldSpec]) -> list[str]:
    return _table(("Field", "Type", "Required", "What it is"), _field_rows(fields))


def format_markdown() -> str:
    """`docs/format.md` — every field a document may carry, by kind."""
    lines = [
        BANNER,
        "",
        "# The document format",
        "",
        "A document is JSON. It says what the diagram **means** — the nodes, the",
        "edges, the words, and a semantic role for each — and it carries no",
        "coordinate, no size and no colour, because those are the tool's output",
        "and never its input. The [refused fields](#what-may-not-be-written) at",
        "the end of this page are that rule made mechanical.",
        "",
        f'Every document declares `"version": {DOCUMENT_VERSION}` and one of the',
        f"{len(KINDS)} kinds. The machine-readable form of this page is the published",
        f"JSON Schema, `{SCHEMA_ID}` — point an editor at it with a `$schema` key and",
        "get completion and inline validation for free.",
        "",
        "```json",
        '{ "$schema": "' + SCHEMA_ID + '", "version": 1, "kind": "flow", "nodes": [] }',
        "```",
        "",
        "`drawspec validate doc.json` prints every violation with the JSON pointer of",
        "the place it was written, so one pass over its output is one edit.",
        "",
        "## Every document",
        "",
        "These fields are legal whatever the kind is.",
        "",
        *_fields_table(COMMON_FIELDS),
        "",
        "## What each kind adds",
        "",
        "The `kind` selects a family, and the family selects which further fields are",
        "legal. A field belonging to another family is refused by name rather than",
        "ignored — a `chart` with `nodes` in it is a mistake worth hearing about.",
        "",
    ]

    for kinds, fields in KIND_PAYLOADS.items():
        heading = _code(kinds)
        lines += [f"### {heading}", "", *_fields_table(fields), ""]

    lines += [
        "## The objects",
        "",
        "What the arrays above hold. Every one of them refuses a field it does not",
        "name, so a misspelt key is an error at the point it was written.",
        "",
    ]

    for name, fields in OBJECTS.items():
        lines += [f"### `{name}` object", "", *_fields_table(fields), ""]

    root_legal = {field.name for field in COMMON_FIELDS} & set(REJECTED_FIELDS)
    lines += [
        "## What may not be written",
        "",
        "Every object above refuses a field it does not name. When the field is one of",
        "these, the refusal says *why* rather than just listing the legal keys — and it",
        "carries the JSON pointer of the place it was written. This is the list that",
        "makes the failures in `docs/brief.md` unexpressible rather than merely",
        "discouraged: a document cannot say where a box goes, so a box cannot go in the",
        "wrong place.",
        "",
        "The *Where* column matters. Most of these names are legal nowhere at all. A",
        "few are legal at the **document root** and refused on everything inside it —",
        f"{_code(sorted(root_legal))} size the canvas, which is a budget for the whole",
        "drawing, and are exactly the wrong thing to say about one box in it.",
        "",
        *_table(
            ("Field", "Where it is refused", "Why not"),
            (
                [
                    f"`{name}`",
                    "On any object — legal at the document root"
                    if name in root_legal
                    else "Everywhere",
                    reason,
                ]
                for name, reason in sorted(REJECTED_FIELDS.items())
            ),
        ),
        "",
    ]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# docs/cli.md — the command line, from the parser
# ---------------------------------------------------------------------------


def _subcommands(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    """The subparsers registered on `parser`, in the order they were added.

    `_SubParsersAction` is argparse's own private name for the action a
    `add_subparsers()` call installs. Reading it is the only way to walk a
    parser's commands, and this is a build-time tool over our own parser, so the
    coupling costs nothing a consumer can feel.
    """
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def _argument_name(action: argparse.Action) -> str:
    if action.option_strings:
        return ", ".join(f"`{option}`" for option in action.option_strings)
    return f"`{action.dest}`"


def _sentence(text: str) -> str:
    """A help string, punctuated, so several of them read as prose side by side."""
    text = text.strip()
    if not text:
        return ""
    text = text[0].upper() + text[1:]
    return text if text.endswith((".", "!", "?")) else text + "."


def _argument_note(action: argparse.Action) -> str:
    """What is written beside an argument: its help, its choices, its default."""
    parts = [_sentence(action.help or "")]
    if action.choices:
        parts.append(f"One of {_code(str(choice) for choice in action.choices)}.")
    # `==SUPPRESS==` is argparse's sentinel for "this flag has no default", worn
    # by --help and --version. Printing it as one is how a reference documents a
    # value that does not exist.
    if (
        action.option_strings
        and action.default not in (None, False)
        and action.default != argparse.SUPPRESS
    ):
        parts.append(f"Default `{action.default}`.")
    return " ".join(part for part in parts if part)


def _arguments_table(command: argparse.ArgumentParser) -> list[str]:
    """Every argument a command takes, minus the two argparse adds itself."""
    rows = [
        [_argument_name(action), _argument_note(action)]
        for action in command._actions
        if not isinstance(action, argparse._HelpAction | argparse._SubParsersAction)
    ]
    return _table(("Argument", "What it does"), rows)


def _command_section(name: str, command: argparse.ArgumentParser) -> list[str]:
    lines = [
        f"### `drawspec {name}`",
        "",
        command.description or "",
        "",
        "```",
        command.format_usage().strip(),
        "```",
        "",
        *_block(_arguments_table(command)),
    ]
    for nested_name, nested in _subcommands(command).items():
        lines += [
            f"#### `drawspec {name} {nested_name}`",
            "",
            nested.description or "",
            "",
            "```",
            nested.format_usage().strip(),
            "```",
            "",
            *_block(_arguments_table(nested)),
        ]
    return lines


def cli_markdown() -> str:
    """`docs/cli.md` — the commands, their arguments, and the exit codes."""
    parser = build_parser()
    lines = [
        BANNER,
        "",
        "# The command line",
        "",
        "```",
        parser.format_usage().strip(),
        "```",
        "",
        "Nothing is printed to stdout but the thing that was asked for — the SVG, the",
        "schema, or a one-line confirmation — so `drawspec render doc.json > doc.svg`",
        "is safe. Refusals go to stderr **in full**: the message names the remedy as",
        "well as the fault, and a build script that truncates it to a summary line is a",
        "build script whose author ends up guessing.",
        "",
        "## Exit codes",
        "",
        "The split is worth stating: **2 is about the invocation, 1 is about the",
        "content.** A misspelt flag or an unknown profile is 2 — nothing was read, so",
        "nothing can be said about it. A document that cannot be read, cannot be parsed,",
        "or cannot be fitted is 1, and a refusal is an outcome, not a crash.",
        "",
        *_table(
            ("Code", "Meaning"),
            [
                [f"`{OK}`", "It worked."],
                [f"`{REFUSED}`", "The document, the theme or the fit was refused."],
                [f"`{USAGE}`", "The command line itself was wrong."],
            ],
        ),
        "",
        "## Global options",
        "",
        "Legal before the command name.",
        "",
        *_block(_arguments_table(parser)),
        "## Commands",
        "",
    ]
    for name, command in _subcommands(parser).items():
        lines += _command_section(name, command)

    lines += [
        "## Embedding profiles",
        "",
        f"`render --profile` takes {_code(PROFILES)}.",
        "",
        "* **`inline`** — for pasting into a Markdown or HTML page. Strokes are",
        "  `currentColor`, so the drawing inherits the page's ink and follows it into",
        "  dark mode; there is no `<style>` block to leak, and every id is scoped so two",
        "  diagrams on one page cannot collide.",
        "* **`standalone`** — for a linked `.svg`, a PDF conversion, or anywhere there",
        "  is nothing to inherit from. `currentColor` is resolved to the theme's",
        "  `[canvas] ink`, because a converter's own default is not a design decision.",
        "",
        "## Themes",
        "",
        "`--theme` takes a bundled theme name or the path of a TOML file. See",
        "[the theme reference](theme.md) for every key a theme may set, and",
        "[the guide](guide.md) for how to write one.",
        "",
    ]
    return "\n".join(lines) + "\n"


