"""The three references a consumer needs, generated from the code they describe.

The endgame for this project is that another project — the one whose 89 study
diagrams are the reason drawspec exists — can adopt it *without reading the
source*. Three things stood between it and that: what a document may contain,
what the command line takes, and what a theme may set. All three are already
written down inside the code, exactly once, and all three were only readable by
opening a module.

So this is a third rendering of things that already have one, on the same
principle `drawspec.schema` states for the JSON Schema: **one description, many
renderings**. Nothing here is a second source of truth.

* `docs/format.md` — the field tables in `drawspec.schema`, the same ones the
  published JSON Schema is generated from.
* `docs/cli.md` — the argument parser in `drawspec.cli`, walked.
* `docs/theme.md` — the theme dataclasses in `drawspec.theme`, their attribute
  docstrings, and the *effective* defaults, which are the bundled default
  theme's values rather than the dataclasses' own, because every consumer theme
  is merged over that file.

A generated document that is committed can drift from its source, so it is not
allowed to: `tests/test_docs.py` regenerates and compares, and `make docs`
rewrites. This is the arrangement `schema/drawspec-v1.schema.json` already has.

Not shipped code. Usage, from the repository root:

    uv run python tools/docs.py            # write the three references
    uv run python tools/docs.py --check    # report drift, write nothing
"""

