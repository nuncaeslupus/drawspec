# docs/theme.md — the theme keys, from the dataclasses
# ---------------------------------------------------------------------------

#: `[section]` in a theme file → the dataclass that reads it. Ordered as a
#: theme file reads: the canvas, then the type, then the things drawn on it.
THEME_SECTIONS: Final[Mapping[str, type]] = {
    "canvas": Canvas,
    "font": FontStacks,
    "scale": TypeScale,
    "fit": FitBand,
    "box": BoxStyle,
    "edge": EdgeStyle,
    "mark": MarkStyle,
    "title": TitleStyle,
    "cycle": CycleStyle,
}

#: Closed vocabularies, by the key that is checked against them. The values are
#: the constants themselves, so a vocabulary that gains a member cannot leave
#: this page stale — only a *new* constrained key needs adding here.
THEME_VOCABULARIES: Final[Mapping[tuple[str, str], tuple[str, ...]]] = {
    ("canvas", "width_mode"): WIDTH_MODES,
    ("font", "default"): FONT_ROLES,
    ("mark", "fills"): FILL_PATTERNS,
    ("title", "level"): TYPE_LEVELS,
    ("cycle", "connector"): CYCLE_CONNECTORS,
}


def attribute_docs(cls: type) -> dict[str, str]:
    """Each field's own docstring — the string literal written under it.

    Python discards these at runtime, which is why they are read back out of the
    source. They are where the *reason* for a value lives, and the reason is the
    part a theme author needs; the first paragraph is the summary and the rest is
    the argument, so only the first paragraph comes here.
    """
    tree = ast.parse(textwrap.dedent(inspect.getsource(cls)))
    definition = tree.body[0]
    if not isinstance(definition, ast.ClassDef):  # pragma: no cover — always a class
        return {}

    docs: dict[str, str] = {}
    previous: str | None = None
    for statement in definition.body:
        if isinstance(statement, ast.AnnAssign) and isinstance(statement.target, ast.Name):
            previous = statement.target.id
            continue
        literal = (
            statement.value
            if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Constant)
            else None
        )
        if previous and literal is not None and isinstance(literal.value, str):
            docs[previous] = textwrap.dedent(literal.value).strip().split("\n\n")[0]
        previous = None
    return docs


def _section_rows(section: str, cls: type, values: Any) -> list[list[str]]:
    docs = attribute_docs(cls)
    rows = []
    for field in dataclasses.fields(cls):
        value = getattr(values, field.name)
        vocabulary = THEME_VOCABULARIES.get((section, field.name))
        described = docs.get(field.name, "")
        if vocabulary:
            each = "Each one of" if isinstance(value, tuple) else "One of"
            described = f"{described} {each} {_code(vocabulary)}.".strip()
        rows.append([f"`{field.name}`", _value(value), described])
    return rows


def _role_rows(roles: Mapping[str, Any]) -> list[list[str]]:
    return [
        [f"`{name}`"] + [_value(getattr(role, field.name)) for field in dataclasses.fields(role)]
        for name, role in roles.items()
    ]


def theme_markdown() -> str:
    """`docs/theme.md` — every key a theme may set, and what the default sets it to."""
    default = load_theme(None)
    lines = [
        BANNER,
        "",
        "# The theme reference",
        "",
        "A theme is **data, not code**: a TOML file a consumer versions and diffs",
        "without importing drawspec. It owns every appearance decision — type size,",
        "stroke weight, shape per role, the canvas width — so that no document has to,",
        "and so that changing one changes every diagram at once.",
        "",
        f"Every theme declares `version = {THEME_VERSION}`, and that is the one key not",
        "inherited: a file must state which format it was written against, or a future",
        "v2 would load as a v1. Everything else is **merged over the bundled default**,",
        "leaf by leaf, so a theme declares only what it changes. The values in the",
        "*Default* columns below are therefore what a key holds if a theme is silent",
        "about it — they are read from the bundled `default.toml`, not from the code's",
        "own fallbacks.",
        "",
        "```toml",
        "version = 1",
        'name = "house"',
        "",
        "[scale]",
        "body = 12.0        # everything else keeps the default",
        "```",
        "",
        "`drawspec theme check house.toml` loads it and runs its invariants.",
        "[The guide](guide.md#writing-a-theme) walks through writing one.",
        "",
        "## The greyscale invariant",
        "",
        "Two roles may not be distinguishable **by colour alone**. The loader compares",
        "every pair and refuses the theme if a pair differs in no other channel, which",
        "is why the tables below carry `shape`, `dash`, `fill_pattern` and",
        "`stroke_width` beside `stroke`: those are what has to do the work. A diagram",
        "that loses its meaning in a black-and-white printout is a diagram that lost it",
        "in dark mode too, and neither is caught by looking at the screen it was made",
        "on.",
        "",
        "Colour is not forbidden — the bundled `accent` theme uses it. It may *point*,",
        "and it may never *carry*.",
        "",
        "## Sections",
        "",
    ]

    for section, cls in THEME_SECTIONS.items():
        summary = (inspect.getdoc(cls) or "").split("\n\n")[0]
        lines += [
            f"### `[{section}]`",
            "",
            summary,
            "",
            *_table(
                ("Key", "Default", "What it is"),
                _section_rows(section, cls, getattr(default, section)),
            ),
            "",
        ]

    lines += [
        "## `[role.*]` — the node roles",
        "",
        "A document names a role; the theme decides what that role looks like. The",
        f"vocabulary is closed: {_code(default.roles)}. `shape` is one of",
        f"{_code(NODE_SHAPES)} and `fill_pattern` one of {_code(FILL_PATTERNS)}.",
        "",
        *_table(
            (
                "Role",
                *(
                    f"`{field.name}`"
                    for field in dataclasses.fields(next(iter(default.roles.values())))
                ),
            ),
            _role_rows(default.roles),
        ),
        "",
        "## `[edge_role.*]` — the edge roles",
        "",
        "The same arrangement for connectors, and it is where a connector that is *not*",
        "an arrow lives: an author says two things are merely associated (`link`) and",
        "the theme decides that means a line with no head. `head` and `tail` are each",
        f"one of {_code(EDGE_HEADS)}.",
        "",
        *_table(
            (
                "Role",
                *(
                    f"`{field.name}`"
                    for field in dataclasses.fields(next(iter(default.edge_roles.values())))
                ),
            ),
            _role_rows(default.edge_roles),
        ),
        "",
        "## The bundled themes",
        "",
        *_table(
            ("Theme", "What it is for"),
            [
                [
                    "`default`",
                    "Ink only. Every stroke is `currentColor`, so a diagram follows its page.",
                ],
                [
                    "`accent`",
                    "Colour that points and never carries: six roles are coloured, and every one "
                    "of them already differed from its neighbours by weight, dash or shape.",
                ],
                [
                    "`wheel`",
                    'The broad tapered cycle connector — `[cycle] connector = "band"` — for a '
                    "cycle drawn loudly.",
                ],
            ],
        ),
        "",
    ]
    return "\n".join(lines) + "\n"


